let currentLang = "nl";

function t(key, vars = {}) {
  const parts = key.split(".");
  let value = MESSAGES[currentLang];
  for (const part of parts) {
    value = value?.[part];
  }
  if (typeof value !== "string") return key;
  return Object.entries(vars).reduce((str, [k, v]) => str.replace(`{${k}}`, v), value);
}

function getLang() {
  return currentLang;
}

function setLang(lang) {
  if (!MESSAGES[lang]) return;
  currentLang = lang;
  localStorage.setItem(LANG_STORAGE_KEY, lang);
  document.documentElement.lang = lang;
  applyI18n();
  document.dispatchEvent(new CustomEvent("langchange"));
}

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    const attr = el.dataset.i18nAttr;
    const value = t(key);
    if (attr) el.setAttribute(attr, value);
    else el.textContent = value;
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });

  document.querySelectorAll("optgroup[data-i18n-label]").forEach((el) => {
    el.label = t(el.dataset.i18nLabel);
  });

  const titleKey = document.body.dataset.i18nTitle;
  if (titleKey) document.title = t(titleKey);

  const metaKey = document.body.dataset.i18nMeta;
  if (metaKey) {
    const meta = document.querySelector('meta[name="description"]');
    if (meta) meta.content = t(metaKey);
  } else {
    const meta = document.querySelector('meta[name="description"]');
    if (meta && !document.body.dataset.i18nTitle) meta.content = t("meta.description");
    if (!titleKey) document.title = t("meta.title");
  }

  const langSelect = document.getElementById("lang-select");
  if (langSelect) langSelect.value = currentLang;
  const langGate = document.getElementById("lang-select-gate");
  if (langGate) langGate.value = currentLang;
}

function initI18n() {
  const saved = localStorage.getItem(LANG_STORAGE_KEY);
  const browserLang = navigator.language?.toLowerCase().startsWith("nl") ? "nl" : "en";
  currentLang = MESSAGES[saved] ? saved : browserLang;
  document.documentElement.lang = currentLang;
  applyI18n();

  const langSelect = document.getElementById("lang-select");
  if (langSelect) {
    langSelect.addEventListener("change", (e) => setLang(e.target.value));
  }
}

window.I18n = { t, getLang, setLang, applyI18n, initI18n };

document.addEventListener("DOMContentLoaded", initI18n);